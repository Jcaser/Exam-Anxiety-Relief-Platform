// ── 检索（RAG-lite） ────────────────────────────────────────────────────
// 返回与查询最相关的 top-K 条知识（按关键词命中数 + 主题命中加权排序）。
export function retrieveTopK(query: string, k = 3): KbEntry[] {
  const q = query.toLowerCase();
  const scored = knowledgeBase.map((entry) => {
    let score = 0;
    for (const kw of entry.keywords) {
      if (q.includes(kw.toLowerCase())) score += 1;
    }
    // 主题/分类命中加权
    if (q.includes(entry.topic.toLowerCase())) score += 2;
    if (q.includes(entry.category.toLowerCase())) score += 1;
    return { entry, score };
  });
  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, k)
    .map((s) => s.entry);
}

export function isCrisis(query: string): boolean {
  return crisisKeywords.some((k) => query.includes(k));
}
